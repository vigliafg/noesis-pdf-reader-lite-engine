def _resolve_theme(mode: str) -> str:
    """Headless theme resolution: there is no GUI, so ``system`` → ``dark``."""
    mode = theme.normalize_mode(mode)
    return "dark" if mode == "system" else mode


def _text_key(text: str) -> str:
    """Deterministic short id of a text (stable across app restarts)."""
    return hashlib.sha1(text.encode("utf-8")).hexdigest()


def _strip_header(body: str) -> str:
    """Return the body without the extraction header line.

    The header is a single line ``── … ──`` (it contains ``│`` separators and
    ends with a blank line). It is excluded from the exported body so the CLI
    output matches the desktop batch export.
    """
    first, sep, rest = body.partition("\\n")
    if sep and first.startswith("──") and "│" in first:
        return rest.lstrip("\\n")
    return body
