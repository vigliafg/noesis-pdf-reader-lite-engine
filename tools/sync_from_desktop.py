#!/usr/bin/env python3
"""Synchronise the headless engine from the desktop repository.

The CLI edition reuses the *desktop engine* verbatim. This script:

1. copies the pure engine modules as-is (no edits);
2. regenerates ``main.py`` — the Qt-free core — by slicing the desktop
   ``main.py`` between two stable markers and wrapping the slice with a fixed
   headless header/footer;
3. records the source commit in ``ENGINE_SOURCE.json``.

Run from the repo root::

    python tools/sync_from_desktop.py
    python tools/sync_from_desktop.py --desktop /path/to/noesis-pdf-reader-lite

The desktop repository is the source of truth: never edit the generated
``main.py`` by hand, run this script instead.
"""
