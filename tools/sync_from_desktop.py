def _is_rule(line: str) -> bool:
    s = line.strip()
    return bool(s) and set(s) <= {"═"}


def _slice_core(desktop_main: str) -> str:
    """Return the Qt-free core block of the desktop ``main.py``."""
    lines = desktop_main.splitlines(keepends=True)
    try:
        si = next(i for i, ln in enumerate(lines) if CORE_START in ln)
        ei = next(i for i, ln in enumerate(lines) if CORE_END in ln)
    except StopIteration as exc:  # pragma: no cover — only if markers move
        raise SystemExit(
            f"marker not found in desktop main.py ({exc}); update the markers "
            "in tools/sync_from_desktop.py"
        ) from exc
    # Include the decorative rule line above the start banner.
    if si >= 1 and _is_rule(lines[si - 1]):
        si -= 1
    # Stop just before the decorative rule that precedes the end banner.
    if ei >= 1 and _is_rule(lines[ei - 1]):
        ei -= 1
    return "".join(lines[si:ei])


def _extract_function(text: str, name: str) -> str:
    """Return the source of a top-level ``def name(...)`` block."""
    lines = text.splitlines(keepends=True)
    start = None
    for i, ln in enumerate(lines):
        if ln.startswith(f"def {name}("):
            start = i
            break
    if start is None:
        raise SystemExit(f"function {name!r} not found in desktop main.py")
    end = start + 1
    while end < len(lines):
        s = lines[end]
        if s.startswith(("def ", "class ", "@")):
            break
        end += 1
    return "".join(lines[start:end]).rstrip("\n") + "\n"


def _desktop_commit(desktop: Path) -> str:
    try:
        out = subprocess.run(
            ["git", "-C", str(desktop), "rev-parse", "HEAD"],
            capture_output=True, text=True, check=True, timeout=10,
        )
        return out.stdout.strip()
    except Exception:  # noqa: BLE001 — best effort
        return ""


def build_main_text(desktop_text: str) -> str:
    """Build the headless ``main.py`` from the desktop ``main.py`` source."""
    core = _slice_core(desktop_text)
    extras = "\n".join(_extract_function(desktop_text, n) for n in EXTRAS)
    extras_block = ""
    if extras:
        banner = (
            "\n\n"
            + "# " + "═" * 77 + "\n"
            + "#  pure helpers extracted from the desktop's Qt region\n"
            + "# " + "═" * 77 + "\n\n\n"
        )
        extras_block = banner + extras
    return HEADER + core + extras_block + FOOTER


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--desktop", type=Path, default=DEFAULT_DESKTOP,
        help="path to the desktop repository checkout",
    )
    args = ap.parse_args(argv)
    desktop: Path = args.desktop.resolve()
    desktop_main = desktop / "main.py"
    if not desktop_main.is_file():
        raise SystemExit(f"desktop main.py not found at {desktop_main}")

    # 1. copy the pure engine modules verbatim
    for name in VERBATIM:
        src = desktop / name
        if not src.is_file():
            raise SystemExit(f"missing engine module: {src}")
        (ROOT / name).write_text(src.read_text(encoding="utf-8"), encoding="utf-8")

    # 2. regenerate the headless core
    desktop_text = desktop_main.read_text(encoding="utf-8")
    (ROOT / "main.py").write_text(build_main_text(desktop_text), encoding="utf-8")

    # 3. record the provenance
    meta = {
        "desktop_repo": str(desktop),
        "desktop_commit": _desktop_commit(desktop),
        "synced_at": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
        "verbatim": VERBATIM,
        "core_markers": {"start": CORE_START, "end": CORE_END},
    }
    (ROOT / "ENGINE_SOURCE.json").write_text(
        json.dumps(meta, indent=2) + "\n", encoding="utf-8")

    print(f"synced {len(VERBATIM)} modules + main.py from {desktop}")
    print(f"desktop commit: {meta['desktop_commit'] or '(unknown)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
